#!/usr/bin/env python3
"""Check the sensor node board against the enclosure and keep the two in step.

    "C:\\Program Files\\KiCad\\9.0\\bin\\python.exe" fit_check.py

1. Reads the routed board (pcbs/gos_sensor_node/gos_sensor_node.kicad_pcb) and
   writes pcb_layout.scad: where the board, its holes, the USB-C socket, the
   sensors and the connectors sit in enclosure coordinates. enclosure_gen.scad
   includes that file, so posts, cut-outs, vents and the light window follow
   the board instead of being typed in by hand.
2. Exports the board with its parts as STL (pcb_assembly.stl) and renders the
   board inside the enclosure (fit_check_*.png) with OpenSCAD.
3. Checks the fit and stops with a non-zero exit code on any failure.

Enclosure coordinates (mm): origin at the centre of the outer footprint, on the
underside of the floor; X across the width, Y along the length (front wall with
the USB-C cut-out at -Y), Z up.
"""
import os
import subprocess
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "..", "pcbs", "gos_sensor_node", "gos_sensor_node.kicad_pcb")
KICAD_CLI = r"C:\Program Files\KiCad\9.0\bin\kicad-cli.exe"
OPENSCAD = os.environ.get("OPENSCAD", r"C:\Program Files\OpenSCAD\openscad.exe")

# Enclosure constants (must match enclosure_gen.scad)
ENC_W, ENC_L, ENC_H, WALL = 85.0, 130.0, 45.0, 2.5
POST_H = 5.0                 # PCB standoff height above the floor
PCB_T = 1.6
USB_GAP = 0.3                # USB-C socket face to the inside of the front wall
BATTERY_D, BATTERY_LEN, CRADLE_WALL = 19.0, 68.0, 2.0
ANTENNA_CLEAR = 10.0         # minimum distance from the module antenna edge to the 18650 can

OX, OY = 100.0, 100.0        # board origin used by generate_pcb.py


def fab_box(fp):
    box = None
    for item in fp.GraphicalItems():
        if item.GetLayer() == pcbnew.F_Fab:
            b = item.GetBoundingBox()
            if box is None:
                box = b
            else:
                box.Merge(b)
    return [pcbnew.ToMM(v) for v in (box.GetLeft() - pcbnew.FromMM(OX), box.GetTop() - pcbnew.FromMM(OY),
                                     box.GetRight() - pcbnew.FromMM(OX), box.GetBottom() - pcbnew.FromMM(OY))]


def main():
    board = pcbnew.LoadBoard(BOARD)
    edges = board.GetBoardEdgesBoundingBox()
    bw = pcbnew.ToMM(edges.GetWidth()) - 0.1      # outline line width
    bl = pcbnew.ToMM(edges.GetHeight()) - 0.1
    fps = {fp.GetReference(): fp for fp in board.GetFootprints()}

    usb = fab_box(fps["J1"])
    usb_overhang = usb[3] - bl                    # socket face past the board's bottom edge
    inner_front = -ENC_L / 2 + WALL
    board_front = inner_front + USB_GAP + usb_overhang   # enclosure Y of the board edge with J1
    floor_top = WALL
    pcb_z = floor_top + POST_H

    def enc(x, y):
        """Board mm (KiCad, Y down from the top edge) -> enclosure X, Y."""
        return x - bw / 2, board_front + (bl - y)

    def pos(ref):
        p = fps[ref].GetPosition()
        return enc(pcbnew.ToMM(p.x) - OX, pcbnew.ToMM(p.y) - OY)

    holes = [pos(r) for r in ("H1", "H2", "H3", "H4")]
    usb_x, _ = pos("J1")
    antenna_edge = enc(0, 0)[1]                   # module antenna sits on the board's top edge
    battery_y = ENC_L / 2 - WALL - (BATTERY_D / 2 + CRADLE_WALL) - 0.5

    lines = [
        "// Generated by mechanical/fit_check.py from pcbs/gos_sensor_node/gos_sensor_node.kicad_pcb.",
        "// Do not edit: rerun fit_check.py after changing the board.",
        f"pcb_size = [{bw:.2f}, {bl:.2f}];",
        f"pcb_origin = [{-bw / 2:.3f}, {board_front:.3f}];   // enclosure XY of the board's bottom-left corner",
        f"pcb_z = {pcb_z:.2f};                  // underside of the board",
        f"pcb_thickness = {PCB_T};",
        "pcb_holes = [" + ", ".join(f"[{x:.3f}, {y:.3f}]" for x, y in holes) + "];",
        f"usb_center = [{usb_x:.3f}, {pcb_z + PCB_T + 1.6:.2f}];   // X and Z of the USB-C socket centre",
        "sht40 = [%.3f, %.3f];" % pos("U5"),
        "tsl2591 = [%.3f, %.3f];" % pos("U6"),
        "j4_led_cable = [%.3f, %.3f];" % pos("J4"),
        "j5_battery = [%.3f, %.3f];" % pos("J5"),
        "status_led = [%.3f, %.3f];" % pos("D2"),
        "charge_led = [%.3f, %.3f];" % pos("D1"),
        f"antenna_edge_y = {antenna_edge:.3f};",
        f"battery_center_y = {battery_y:.3f};",
    ]
    with open(os.path.join(HERE, "pcb_layout.scad"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    # ---- checks
    failures = []

    def check(ok, text):
        print(("PASS " if ok else "FAIL ") + text)
        if not ok:
            failures.append(text)

    inner_x = ENC_W / 2 - WALL
    check(all(abs(x) + 3 <= inner_x for x, _ in holes), "mounting posts inside the side walls")
    check(-bw / 2 >= -inner_x and bw / 2 <= inner_x, f"board width {bw:.1f} mm fits the {2 * inner_x:.1f} mm cavity")
    check(abs((board_front - usb_overhang) - (inner_front + USB_GAP)) < 0.01,
          f"USB-C socket face {USB_GAP} mm from the inside of the front wall")
    cradle_front = battery_y - BATTERY_D / 2 - CRADLE_WALL
    check(cradle_front > antenna_edge, "battery cradle behind the board (no overlap)")
    check(cradle_front - antenna_edge >= ANTENNA_CLEAR,
          f"18650 can {cradle_front - antenna_edge:.1f} mm from the module antenna (need {ANTENNA_CLEAR})")
    check(BATTERY_LEN + 2 * CRADLE_WALL <= 2 * inner_x, "18650 cradle fits across the cavity")
    j5x, j5y = pos("J5")
    lead = abs(j5y - battery_y) + abs(j5x)
    check(lead < 150, f"battery lead J5 to cradle about {lead:.0f} mm (a standard 150 mm JST-PH lead reaches)")
    check(pcb_z + PCB_T + 12 < ENC_H, "tallest part (about 12 mm with cable plugs) clears the lid")

    # ---- 3D: board with parts, rendered inside the enclosure
    stl = os.path.join(HERE, "pcb_assembly.stl")
    subprocess.run([KICAD_CLI, "pcb", "export", "stl", "--force", "--drill-origin", "--subst-models",
                    "-o", stl, BOARD], check=True, capture_output=True)
    scad = os.path.join(HERE, "enclosure_gen.scad")
    for name, camera, extra in (
            ("iso", "0,-20,10,55,0,30,320", ["-D", "show_pcb=true", "-D", "show_lid=false"]),
            ("top", "0,0,0,0,0,0,260", ["-D", "show_pcb=true", "-D", "show_lid=false"]),
            ("section", "0,-15,15,90,0,-90,190", ["-D", "show_pcb=true", "-D", "show_lid=true", "-D", "cut=true"])):
        # preview mode (not --render): keeps colours, and CGAL would drop non-manifold part models
        subprocess.run([OPENSCAD, "-o", os.path.join(HERE, f"fit_check_{name}.png"),
                        "--imgsize=1400,1100", f"--camera={camera}", "--viewall" if name == "top" else "--autocenter",
                        *extra, scad], check=True, capture_output=True)
    print("wrote pcb_layout.scad, pcb_assembly.stl, fit_check_iso.png, fit_check_top.png, fit_check_section.png")
    if failures:
        sys.exit(f"{len(failures)} fit check(s) failed")


if __name__ == "__main__":
    main()
